import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const reportPath = join(root, 'conformance', 'api', 'undertone.api.md');

/** Emits declarations for `srcDir` into a temporary directory and returns the path of its index. */
function emitDeclarations(srcDir: string, outDir: string): string {
  const tscBin = join(root, 'node_modules', 'typescript', 'bin', 'tsc');
  execFileSync(
    'node',
    [
      tscBin,
      '--project',
      join(root, 'tsconfig.json'),
      '--emitDeclarationOnly',
      '--declaration',
      '--declarationMap',
      'false',
      '--sourceMap',
      'false',
      '--rootDir',
      srcDir,
      '--outDir',
      outDir
    ],
    { cwd: root, stdio: 'inherit' }
  );
  return join(outDir, 'index.d.ts');
}

/** Builds the report text from the declaration entry point. */
function buildReport(entry: string): string {
  const program = ts.createProgram([entry], {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    skipLibCheck: true
  });
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(entry);
  if (!source) throw new Error(`Cannot read ${entry}`);
  const moduleSymbol = checker.getSymbolAtLocation(source);
  if (!moduleSymbol) throw new Error('index.d.ts has no exports');
  const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });

  const entries: { name: string; text: string }[] = [];
  for (const exported of checker.getExportsOfModule(moduleSymbol)) {
    const target =
      exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
    const declarations = target.declarations ?? [];
    const text = declarations
      .map((declaration) =>
        printer.printNode(ts.EmitHint.Unspecified, declaration, declaration.getSourceFile())
      )
      .map((node) => node.replace(/\r\n/g, '\n').trimEnd())
      .join('\n');
    entries.push({ name: exported.getName(), text });
  }
  entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

  const lines = [
    '# Undertone public API report',
    '',
    'Generated by `bun run api:record` from the declarations `tsc` emits for `src/index.ts`. Every exported name appears once, sorted, with comments removed. Do not edit by hand; review the diff when it changes.',
    ''
  ];
  for (const { name, text } of entries) {
    lines.push(`## ${name}`, '', '```ts', text, '```', '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

/** Generates the report from the current `src/` in a temporary directory. */
export function generate(): string {
  const temp = mkdtempSync(join(tmpdir(), 'undertone-api-'));
  try {
    return buildReport(emitDeclarations(join(root, 'src'), temp));
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
}

const mode = process.argv[2];
if (mode === 'record') {
  writeFileSync(reportPath, generate());
  console.log(`Wrote ${reportPath}`);
} else if (mode === 'check') {
  const fresh = generate();
  const committed = readFileSync(reportPath, 'utf8');
  if (fresh === committed) {
    console.log('API report is up to date.');
  } else {
    const temp = mkdtempSync(join(tmpdir(), 'undertone-api-diff-'));
    const freshPath = join(temp, 'fresh.api.md');
    writeFileSync(freshPath, fresh);
    try {
      execFileSync('diff', ['-u', reportPath, freshPath], { stdio: 'inherit' });
    } catch {
      // diff exits 1 when the files differ, which is the expected case here.
    }
    rmSync(temp, { recursive: true, force: true });
    console.error('\nThe public API changed. Review the diff, then run `bun run api:record`.');
    process.exit(1);
  }
} else {
  console.error('Usage: report.ts record|check');
  process.exit(2);
}
